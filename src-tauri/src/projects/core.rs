    #[test]
    fn note_links_must_point_into_the_project() {
        let st = store("notes-link");
        let p = st.create("Acme", "a3".into(), 100).unwrap();
        st.add(&p.id, "b1".into(), "Port Scanner", "", rep("Scan"), 101)
            .unwrap();
        let mut n = note("e5", "Port Scanner", "about the scan", 1);
        n.item_id = Some("b1".into());
        assert_eq!(
            st.save_note(&p.id, n, "", 1).unwrap().item_id.as_deref(),
            Some("b1")
        );
        let mut n = note("e6", "Port Scanner", "dangling", 2);
        n.item_id = Some("c9".into());
        assert_eq!(st.save_note(&p.id, n, "", 2).unwrap().item_id, None);

        // Removing the result keeps the note but drops the link.
        st.update(&p.id, "Acme", "", &[], 200).unwrap();
        let v = st.get(&p.id).unwrap();
        assert_eq!(v.tool_notes.len(), 2);
        assert!(v.tool_notes.iter().all(|n| n.item_id.is_none()));
    }

    #[test]
    fn notes_sit_after_their_tools_results_in_reports() {
        let st = store("notes-report");
        let p = st.create("Acme", "a4".into(), 100).unwrap();
        st.add(&p.id, "b1".into(), "Port Scanner", "", rep("Scan 1"), 101)
            .unwrap();
        let mut dns = rep("Audit");
        dns.tool = "DNS Analyzer".into();
        st.add(&p.id, "b2".into(), "DNS Analyzer", "", dns, 102)
            .unwrap();
        st.add(&p.id, "b3".into(), "Port Scanner", "", rep("Scan 2"), 103)
            .unwrap();
        // Saved out of order: the report lists them oldest first.
        st.save_note(&p.id, note("e2", "Port Scanner", "second <b>", 20), "", 1)
            .unwrap();
        let mut linked = note("e1", "Port Scanner", "first", 10);
        linked.item_id = Some("b3".into());
        st.save_note(&p.id, linked, "", 1).unwrap();
        st.save_note(&p.id, note("e3", "Wake-on-LAN", "woke lab box", 30), "", 1)
            .unwrap();

        let r = st.report(&p.id, "now").unwrap();
        let titles: Vec<&str> = r.sections.iter().map(|s| s.title.as_str()).collect();
        let scan2 = titles.iter().position(|t| *t == "3. Scan 2").unwrap();
        let notes = titles
            .iter()
            .position(|t| *t == "Notes: Port Scanner")
            .unwrap();
        assert!(notes > scan2, "{titles:?}");
        assert_eq!(
            titles
                .iter()
                .filter(|t| t.starts_with("Notes: Port"))
                .count(),
            1
        );
        let wol = titles.iter().position(|t| *t == "4. Wake-on-LAN").unwrap();
        assert!(r.sections[wol].part);
        assert_eq!(r.sections[wol].subtitle, "Notes only, no saved output");
        assert_eq!(titles[wol + 1], "Notes: Wake-on-LAN");

        let Block::Notes { items } = &r.sections[notes].blocks[0] else {
            panic!("expected notes block");
        };
        assert_eq!(items[0].text, "first");
        assert!(items[0].heading.contains("(America/New_York)"));
        assert!(items[0].heading.contains("about result 3: Scan 2"));
        assert_eq!(items[1].text, "second <b>");

        // The HTML export escapes note text.
        let html = String::from_utf8(report::render(&r, Format::Html).unwrap()).unwrap();
        assert!(html.contains("second &lt;b&gt;"));
    }

