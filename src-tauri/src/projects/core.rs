//! Projects: named collections of tool results (reports) that export together
//! as one combined report. Each project is one JSON file, `<id>.json`, in a
//! directory the caller chooses (normally `<app data>/projects`).
//!
//! Ids are generated here and validated as short lowercase hex before any path
//! is built, so the UI cannot name arbitrary files. Writes are atomic and
//! sizes are capped. Time is passed in by the caller so tests are
//! deterministic.

use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU32, Ordering};

use serde::de::IgnoredAny;
use serde::{Deserialize, Serialize};
use thiserror::Error;

use crate::report::core::{self as report, Block, KeyValue, NoteEntry, Report, Section};
use crate::store::core::write_atomic;

/// Largest project file accepted, on load and on save.
pub const MAX_PROJECT_BYTES: usize = 25_000_000;
/// Most results in one project.
pub const MAX_ITEMS: usize = 500;
/// Most projects kept.
pub const MAX_PROJECTS: usize = 1000;
/// Longest project or result name, in characters.
pub const MAX_NAME: usize = 200;
/// Longest notes field, in characters.
pub const MAX_NOTE: usize = 20_000;
/// Most timestamped tool notes in one project.
pub const MAX_TOOL_NOTES: usize = 2000;
/// Longest id accepted.
const MAX_ID: usize = 32;
/// On-disk format version.
const VERSION: u32 = 1;

#[derive(Debug, Error, PartialEq, Eq)]
pub enum ProjectError {
    #[error("invalid project or item id")]
    InvalidId,
    #[error("project not found")]
    NotFound,
    #[error("name is too long (limit {MAX_NAME} characters)")]
    NameTooLong,
    #[error("notes are too long (limit {MAX_NOTE} characters)")]
    NoteTooLong,
    #[error("too many notes in this project (limit {MAX_TOOL_NOTES})")]
    TooManyNotes,
    #[error("a note needs some text")]
    EmptyNote,
    #[error("project is full (limit {MAX_ITEMS} results)")]
    TooManyItems,
    #[error("too many projects (limit {MAX_PROJECTS}); delete some first")]
    TooManyProjects,
    #[error("project would be too large ({0} bytes; limit {MAX_PROJECT_BYTES})")]
    TooLarge(usize),
    #[error("project file is unreadable: {0}")]
    Corrupt(String),
    #[error("{0}")]
    Report(#[from] report::ReportError),
    #[error("{0}")]
    Io(String),
}

/// One saved result: a tool's report plus the user's title and note.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct Item {
    pub id: String,
    pub tool: String,
    pub title: String,
    #[serde(default)]
    pub note: String,
    /// Unix seconds.
    pub added: u64,
    /// When it was added, in the user's locale, for reports.
    #[serde(default)]
    pub added_label: String,
    pub report: Report,
}

/// A timestamped, plain-text note about one tool's work in a project. The
/// project and tool are fixed when the note is started; edits keep the
/// original creation time and record the last edit separately.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct ToolNote {
    /// Generated by the UI when the draft starts, so saving twice updates
    /// the same note instead of adding a duplicate.
    pub id: String,
    /// Tool display name, as it appears in reports.
    pub tool: String,
    /// Tool registry id, for filtering in the UI.
    #[serde(default)]
    pub tool_id: String,
    pub text: String,
    /// Unix milliseconds.
    pub created: u64,
    /// Creation time with time zone, in the user's locale.
    pub created_label: String,
    /// IANA time zone at creation, e.g. America/New_York.
    #[serde(default)]
    pub time_zone: String,
    #[serde(default)]
    pub edited: Option<u64>,
    #[serde(default)]
    pub edited_label: String,
    /// Optional link to one saved result in the same project.
    #[serde(default)]
    pub item_id: Option<String>,
}

/// What the UI sends to save a note.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct NoteInput {
    pub id: String,
    pub tool: String,
    #[serde(default)]
    pub tool_id: String,
    pub text: String,
    pub created: u64,
    pub created_label: String,
    #[serde(default)]
    pub time_zone: String,
    #[serde(default)]
    pub item_id: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct Project {
    pub version: u32,
    pub id: String,
    pub name: String,
    #[serde(default)]
    pub notes: String,
    /// Unix seconds.
    pub created: u64,
    pub updated: u64,
    pub items: Vec<Item>,
    #[serde(default)]
    pub tool_notes: Vec<ToolNote>,
}

/// List entry, without the item contents.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct ProjectSummary {
    pub id: String,
    pub name: String,
    pub created: u64,
    pub updated: u64,
    pub items: usize,
}

/// An item as the panel shows it: metadata and section titles only.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct ItemView {
    pub id: String,
    pub tool: String,
    pub title: String,
    pub note: String,
    pub added: u64,
    pub added_label: String,
    pub sections: Vec<String>,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct ProjectView {
    pub id: String,
    pub name: String,
    pub notes: String,
    pub created: u64,
    pub updated: u64,
    pub items: Vec<ItemView>,
    pub tool_notes: Vec<ToolNote>,
}

/// The panel's edit of one item. The order of edits is the new item order;
/// items left out are removed.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ItemEdit {
    pub id: String,
    pub title: String,
    #[serde(default)]
    pub note: String,
}

/// Just enough of a project file to list it, skipping item contents.
#[derive(Deserialize)]
struct Head {
    id: String,
    name: String,
    created: u64,
    updated: u64,
    items: Vec<IgnoredAny>,
}

/// Lowercase hex, 1 to 32 characters.
pub fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= MAX_ID
        && id
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

static COUNTER: AtomicU32 = AtomicU32::new(0);

/// A new id from a nanosecond timestamp and a process-wide counter.
pub fn new_id(now_nanos: u128) -> String {
    let n = COUNTER.fetch_add(1, Ordering::Relaxed) & 0xffff;
    format!("{:x}{n:04x}", now_nanos & 0xffff_ffff_ffff_ffff)
}

fn clean_name(name: &str, fallback: &str) -> Result<String, ProjectError> {
    let name = name.trim();
    if name.chars().count() > MAX_NAME {
        return Err(ProjectError::NameTooLong);
    }
    Ok(if name.is_empty() {
        fallback.to_string()
    } else {
        name.to_string()
    })
}

fn check_note(note: &str) -> Result<(), ProjectError> {
    if note.chars().count() > MAX_NOTE {
        Err(ProjectError::NoteTooLong)
    } else {
        Ok(())
    }
}

impl Project {
    fn summary(&self) -> ProjectSummary {
        ProjectSummary {
            id: self.id.clone(),
            name: self.name.clone(),
            created: self.created,
            updated: self.updated,
            items: self.items.len(),
        }
    }

    fn view(&self) -> ProjectView {
        ProjectView {
            id: self.id.clone(),
            name: self.name.clone(),
            notes: self.notes.clone(),
            created: self.created,
            updated: self.updated,
            items: self
                .items
                .iter()
                .map(|i| ItemView {
                    id: i.id.clone(),
                    tool: i.tool.clone(),
                    title: i.title.clone(),
                    note: i.note.clone(),
                    added: i.added,
                    added_label: i.added_label.clone(),
                    sections: i.report.sections.iter().map(|s| s.title.clone()).collect(),
                })
                .collect(),
            tool_notes: self.tool_notes.clone(),
        }
    }
}

/// Project files in one directory.
pub struct ProjectStore {
    dir: PathBuf,
}

impl ProjectStore {
    pub fn new(dir: impl Into<PathBuf>) -> Self {
        Self { dir: dir.into() }
    }

    fn path(&self, id: &str) -> PathBuf {
        self.dir.join(format!("{id}.json"))
    }

    /// Ids of every project file present.
    fn ids(&self) -> Result<Vec<String>, ProjectError> {
        let entries = match fs::read_dir(&self.dir) {
            Ok(e) => e,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
            Err(e) => {
                return Err(ProjectError::Io(format!(
                    "could not read {}: {e}",
                    self.dir.display()
                )));
            }
        };
        Ok(entries
            .filter_map(|e| e.ok())
            .filter_map(|e| {
                let name = e.file_name().into_string().ok()?;
                let id = name.strip_suffix(".json")?;
                valid_id(id).then(|| id.to_string())
            })
            .collect())
    }

    fn read_bytes(&self, id: &str) -> Result<Vec<u8>, ProjectError> {
        if !valid_id(id) {
            return Err(ProjectError::InvalidId);
        }
        let path = self.path(id);
        let meta = match fs::metadata(&path) {
            Ok(m) => m,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                return Err(ProjectError::NotFound);
            }
            Err(e) => {
                return Err(ProjectError::Io(format!(
                    "could not read {}: {e}",
                    path.display()
                )));
            }
        };
        if meta.len() > MAX_PROJECT_BYTES as u64 {
            return Err(ProjectError::TooLarge(meta.len() as usize));
        }
        fs::read(&path)
            .map_err(|e| ProjectError::Io(format!("could not read {}: {e}", path.display())))
    }

    fn read(&self, id: &str) -> Result<Project, ProjectError> {
        let bytes = self.read_bytes(id)?;
        serde_json::from_slice(&bytes).map_err(|e| ProjectError::Corrupt(e.to_string()))
    }

    fn write(&self, p: &Project) -> Result<(), ProjectError> {
        let bytes = serde_json::to_vec(p).map_err(|e| ProjectError::Io(e.to_string()))?;
        if bytes.len() > MAX_PROJECT_BYTES {
            return Err(ProjectError::TooLarge(bytes.len()));
        }
        write_atomic(&self.dir, &format!("{}.json", p.id), &bytes).map_err(ProjectError::Io)
    }

    /// Every readable project, most recently updated first. Unreadable files
    /// are skipped, not deleted.
    pub fn list(&self) -> Result<Vec<ProjectSummary>, ProjectError> {
        let mut out = Vec::new();
        for id in self.ids()? {
            let Ok(bytes) = self.read_bytes(&id) else {
                continue;
            };
            let Ok(h) = serde_json::from_slice::<Head>(&bytes) else {
                continue;
            };
            if h.id != id {
                continue;
            }
            out.push(ProjectSummary {
                id: h.id,
                name: h.name,
                created: h.created,
                updated: h.updated,
                items: h.items.len(),
            });
        }
        out.sort_by(|a, b| b.updated.cmp(&a.updated).then_with(|| a.name.cmp(&b.name)));
        Ok(out)
    }

    pub fn create(&self, name: &str, id: String, now: u64) -> Result<ProjectSummary, ProjectError> {
        if !valid_id(&id) {
            return Err(ProjectError::InvalidId);
        }
        if self.ids()?.len() >= MAX_PROJECTS {
            return Err(ProjectError::TooManyProjects);
        }
        let p = Project {
            version: VERSION,
            id,
            name: clean_name(name, "Untitled project")?,
            notes: String::new(),
            created: now,
            updated: now,
            items: Vec::new(),
            tool_notes: Vec::new(),
        };
        self.write(&p)?;
        Ok(p.summary())
    }

    pub fn get(&self, id: &str) -> Result<ProjectView, ProjectError> {
        Ok(self.read(id)?.view())
    }

    /// Apply the panel's edits: name, notes, and item order, titles and notes.
    pub fn update(
        &self,
        id: &str,
        name: &str,
        notes: &str,
        edits: &[ItemEdit],
        now: u64,
    ) -> Result<ProjectView, ProjectError> {
        let mut p = self.read(id)?;
        p.name = clean_name(name, "Untitled project")?;
        check_note(notes)?;
        p.notes = notes.to_string();

        let mut old = std::mem::take(&mut p.items);
        for edit in edits {
            check_note(&edit.note)?;
            let Some(pos) = old.iter().position(|i| i.id == edit.id) else {
                continue;
            };
            let mut item = old.swap_remove(pos);
            item.title = clean_name(&edit.title, &item.report.title)?;
            item.note = edit.note.clone();
            p.items.push(item);
        }
        // Notes linked to a removed result keep their text, without the link.
        for n in &mut p.tool_notes {
            if n.item_id
                .as_ref()
                .is_some_and(|iid| !p.items.iter().any(|i| &i.id == iid))
            {
                n.item_id = None;
            }
        }
        p.updated = now;
        self.write(&p)?;
        Ok(p.view())
    }

    pub fn delete(&self, id: &str) -> Result<(), ProjectError> {
        if !valid_id(id) {
            return Err(ProjectError::InvalidId);
        }
        match fs::remove_file(self.path(id)) {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Err(ProjectError::NotFound),
            Err(e) => Err(ProjectError::Io(e.to_string())),
        }
    }

    /// Add a tool's report to a project.
    pub fn add(
        &self,
        id: &str,
        item_id: String,
        tool: &str,
        added_label: &str,
        report: Report,
        now: u64,
    ) -> Result<ProjectSummary, ProjectError> {
        if !valid_id(&item_id) {
            return Err(ProjectError::InvalidId);
        }
        report::validate(&report)?;
        let mut p = self.read(id)?;
        if p.items.len() >= MAX_ITEMS {
            return Err(ProjectError::TooManyItems);
        }
        let title = clean_name(&report.title, "Untitled result")
            .unwrap_or_else(|_| report.title.chars().take(MAX_NAME).collect());
        p.items.push(Item {
            id: item_id,
            tool: tool.to_string(),
            title,
            note: String::new(),
            added: now,
            added_label: added_label.to_string(),
            report,
        });
        p.updated = now;
        self.write(&p)?;
        Ok(p.summary())
    }

    /// Save a tool note: add it, or update the text and link of the note with
    /// the same id. The tool and creation time of an existing note never
    /// change. Saving unchanged text is a no-op, so repeated saves do not
    /// bump the edit time.
    pub fn save_note(
        &self,
        id: &str,
        input: NoteInput,
        edited_label: &str,
        now_ms: u64,
    ) -> Result<ToolNote, ProjectError> {
        if !valid_id(&input.id) {
            return Err(ProjectError::InvalidId);
        }
        if input.text.trim().is_empty() {
            return Err(ProjectError::EmptyNote);
        }
        check_note(&input.text)?;
        if input.tool.chars().count() > MAX_NAME
            || input.tool_id.chars().count() > MAX_NAME
            || input.created_label.chars().count() > MAX_NAME
            || input.time_zone.chars().count() > MAX_NAME
            || edited_label.chars().count() > MAX_NAME
        {
            return Err(ProjectError::NameTooLong);
        }
        let mut p = self.read(id)?;
        // A link to a result that is not in this project is dropped.
        let item_id = input
            .item_id
            .filter(|iid| p.items.iter().any(|i| &i.id == iid));

        let saved = if let Some(n) = p.tool_notes.iter_mut().find(|n| n.id == input.id) {
            if n.text == input.text && n.item_id == item_id {
                return Ok(n.clone());
            }
            n.text = input.text;
            n.item_id = item_id;
            n.edited = Some(now_ms);
            n.edited_label = edited_label.to_string();
            n.clone()
        } else {
            if p.tool_notes.len() >= MAX_TOOL_NOTES {
                return Err(ProjectError::TooManyNotes);
            }
            let note = ToolNote {
                id: input.id,
                tool: clean_name(&input.tool, "Notes")?,
                tool_id: input.tool_id,
                text: input.text,
                created: input.created,
                created_label: input.created_label,
                time_zone: input.time_zone,
                edited: None,
                edited_label: String::new(),
                item_id,
            };
            p.tool_notes.push(note.clone());
            note
        };
        p.updated = now_ms / 1000;
        self.write(&p)?;
        Ok(saved)
    }

    /// Delete one tool note. Deleting a note that is already gone is fine.
    pub fn delete_note(&self, id: &str, note_id: &str, now: u64) -> Result<(), ProjectError> {
        if !valid_id(note_id) {
            return Err(ProjectError::InvalidId);
        }
        let mut p = self.read(id)?;
        let before = p.tool_notes.len();
        p.tool_notes.retain(|n| n.id != note_id);
        if p.tool_notes.len() != before {
            p.updated = now;
            self.write(&p)?;
        }
        Ok(())
    }

    /// The combined report for a project.
    pub fn report(&self, id: &str, generated: &str) -> Result<Report, ProjectError> {
        Ok(combined_report(&self.read(id)?, generated))
    }
}

/// Heading shown above one note in reports.
fn note_heading(n: &ToolNote, p: &Project) -> String {
    let mut parts = vec![n.created_label.clone()];
    if !n.time_zone.is_empty() && !n.created_label.contains(&n.time_zone) {
        parts[0] = format!("{} ({})", n.created_label, n.time_zone);
    }
    if n.edited.is_some() && !n.edited_label.is_empty() {
        parts.push(format!("edited {}", n.edited_label));
    }
    if let Some(iid) = &n.item_id
        && let Some((pos, item)) = p.items.iter().enumerate().find(|(_, i)| &i.id == iid)
    {
        parts.push(format!("about result {}: {}", pos + 1, item.title));
    }
    parts.join(" | ")
}

/// A tool's notes, oldest first, as one report section.
fn notes_section(p: &Project, tool: &str) -> Option<Section> {
    let mut notes: Vec<&ToolNote> = p.tool_notes.iter().filter(|n| n.tool == tool).collect();
    if notes.is_empty() {
        return None;
    }
    notes.sort_by_key(|n| n.created);
    Some(Section {
        title: format!("Notes: {tool}"),
        subtitle: format!(
            "{} note{}",
            notes.len(),
            if notes.len() == 1 { "" } else { "s" }
        ),
        blocks: vec![Block::Notes {
            items: notes
                .iter()
                .map(|n| NoteEntry {
                    heading: note_heading(n, p),
                    text: n.text.trim_end().to_string(),
                })
                .collect(),
        }],
        part: false,
    })
}

/// Build one report from every item: optional notes, a contents table, then a
/// part heading per item followed by that item's sections. Each tool's notes
/// follow the last result from that tool; tools with notes but no saved
/// result get their own labeled part at the end.
pub fn combined_report(p: &Project, generated: &str) -> Report {
    let mut sections = Vec::new();
    // Tools with notes but no saved result, in order of their first note.
    let mut notes_only: Vec<&str> = Vec::new();
    let mut by_time: Vec<&ToolNote> = p.tool_notes.iter().collect();
    by_time.sort_by_key(|n| n.created);
    for n in by_time {
        if !p.items.iter().any(|i| i.tool == n.tool) && !notes_only.contains(&n.tool.as_str()) {
            notes_only.push(&n.tool);
        }
    }

    let mut overview = vec![Block::KeyValues {
        items: vec![
            KeyValue {
                key: "Project".to_string(),
                value: p.name.clone(),
            },
            KeyValue {
                key: "Results".to_string(),
                value: p.items.len().to_string(),
            },
            KeyValue {
                key: "Notes".to_string(),
                value: p.tool_notes.len().to_string(),
            },
        ],
    }];
    if !p.notes.trim().is_empty() {
        overview.push(Block::Paragraph {
            text: p.notes.trim().to_string(),
        });
    }
    if !p.items.is_empty() || !notes_only.is_empty() {
        let mut rows: Vec<Vec<String>> = p
            .items
            .iter()
            .enumerate()
            .map(|(n, i)| {
                vec![
                    (n + 1).to_string(),
                    i.title.clone(),
                    i.tool.clone(),
                    i.added_label.clone(),
                ]
            })
            .collect();
        for (k, tool) in notes_only.iter().enumerate() {
            rows.push(vec![
                (p.items.len() + k + 1).to_string(),
                "Notes only (no saved output)".to_string(),
                tool.to_string(),
                String::new(),
            ]);
        }
        overview.push(Block::Table {
            headers: vec!["#".into(), "Result".into(), "Tool".into(), "Added".into()],
            rows,
        });
    }
    sections.push(Section {
        title: "Overview".to_string(),
        blocks: overview,
        ..Default::default()
    });

    for (n, item) in p.items.iter().enumerate() {
        let mut sub = vec![item.tool.clone()];
        if !item.added_label.is_empty() {
            sub.push(item.added_label.clone());
        }
        let mut blocks = Vec::new();
        if !item.report.subtitle.is_empty() {
            blocks.push(Block::Paragraph {
                text: item.report.subtitle.clone(),
            });
        }
        if !item.note.trim().is_empty() {
            blocks.push(Block::Paragraph {
                text: format!("Note: {}", item.note.trim()),
            });
        }
        sections.push(Section {
            title: format!("{}. {}", n + 1, item.title),
            subtitle: sub.join(" | "),
            blocks,
            part: true,
        });
        sections.extend(item.report.sections.iter().cloned().map(|mut s| {
            s.part = false;
            s
        }));
        let last_of_tool = !p.items[n + 1..].iter().any(|i| i.tool == item.tool);
        if last_of_tool && let Some(s) = notes_section(p, &item.tool) {
            sections.push(s);
        }
    }

    for (k, tool) in notes_only.iter().enumerate() {
        sections.push(Section {
            title: format!("{}. {tool}", p.items.len() + k + 1),
            subtitle: "Notes only, no saved output".to_string(),
            blocks: Vec::new(),
            part: true,
        });
        if let Some(s) = notes_section(p, tool) {
            sections.push(s);
        }
    }

    Report {
        title: p.name.clone(),
        subtitle: {
            let plural = |n: usize| if n == 1 { "" } else { "s" };
            let mut sub = format!("{} result{}", p.items.len(), plural(p.items.len()));
            if !p.tool_notes.is_empty() {
                sub.push_str(&format!(
                    ", {} note{}",
                    p.tool_notes.len(),
                    plural(p.tool_notes.len())
                ));
            }
            sub
        },
        generated: generated.to_string(),
        tool: "Projects".to_string(),
        sections,
    }
}

/// Directory for project files under the app data dir.
pub fn projects_dir(app_data: &Path) -> PathBuf {
    app_data.join("projects")
}

